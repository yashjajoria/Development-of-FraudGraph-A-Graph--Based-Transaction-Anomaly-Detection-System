"""Action tools (13-14): requires_confirmation=True. The registry refuses to run them unless confirmed=True."""
from app.services.copilot.data import get_store
from app.services.copilot.tools.read import acct, mask
from app.services.copilot.tools.registry import ToolError, inr, obj, registry

STATUSES = ["open", "investigating", "confirmed_fraud", "false_positive", "closed"]


@registry.register("Change an alert's status with a note. Needs analyst confirmation.",
                   obj({"alert_id": {"type": "string", "pattern": r"^ALR_\d+$"}, "status": {"type": "string", "enum": STATUSES},
                        "note": {"type": "string", "maxLength": 500}}, ("alert_id", "status")),
                   requires_confirmation=True)
def update_alert_status(alert_id: str, status: str, note: str = "") -> dict:
    a = get_store().alerts.get(alert_id)
    if not a:
        raise ToolError(f"Alert {alert_id} not found")
    old, a["status"] = a["status"], status
    if note:
        a["notes"].append(note)
    return {"data": {"alert_id": alert_id, "old_status": old, "new_status": status}, "referenced_nodes": [a["account_id"]],
            "summary": f"Alert {alert_id} changed from {old} to {status}"}


@registry.register("Generate a case report for an account. Needs analyst confirmation.",
                   obj({"account_id": {"type": "string", "pattern": r"^ACC_\d+$"}}, ("account_id",)),
                   requires_confirmation=True)
def generate_case_report(account_id: str) -> dict:
    s, a = get_store(), acct(account_id)
    r, f = s.risk[account_id], s.features[account_id]
    md = "\n".join([
        f"# Case report: {account_id}", f"- Type: {a['type']}  |  Device: {a['device_id']}  |  Community: {a['community_id']}",
        f"- Contact: phone {mask(a['phone'])}, card {mask(a['card'])}",
        f"- Risk: {r['score']} ({r['level']})", f"- Received {inr(f['total_in'])} from {f['unique_senders']} accounts; "
        f"sent {inr(f['total_out'])} to {f['unique_receivers']} accounts", "## Triggered rules",
        *[f"- {x['name']}: {x['detail']}" for x in r["rules"]], "## Alerts",
        *[f"- {x['id']}: {x['status']}" for x in s.alerts.values() if x["account_id"] == account_id],
        "", "_Generated by FraudGraph Copilot; analyst review required._"])
    return {"data": {"markdown": md}, "referenced_nodes": [account_id], "summary": f"Case report generated for {account_id}"}
